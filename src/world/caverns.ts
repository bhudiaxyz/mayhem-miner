export const CAVERNS: Cavern[] = DEFS.map(parse);

export function parse(def: Def, n: number): Cavern {
    if (def.rows.length !== H - 2) throw new Error(`${def.name}: needs ${H - 2} rows`);
    const grid: string[] = [];
    grid.push("#".repeat(W));
    for (const row of def.rows) {
        if (row.length > W - 2) throw new Error(`${def.name}: row too long: ${row}`);
        grid.push("#" + row.padEnd(W - 2, ".") + "#");
    }
    grid.push("#".repeat(W));
    const cells = grid.join("").split("");
    const cv: Cavern = {
        n,
        name: def.name,
        air: 75 - n,
        tiles: "",
        start: { c: 1, r: 14 },
        portal: { c: 28, r: 13 },
        crystals: [],
        levers: [],
        guardians: [],
    };
    const marks: [string, number, number][] = [];
    cells.forEach((ch, i) => {
        if (!"SP*kEeVv".includes(ch)) return;
        marks.push([ch, i % W, Math.floor(i / W)]);
        cells[i] = ".";
    });
    const at = (c: number, r: number) => (c < 0 || c >= W || r < 0 || r >= H ? "#" : cells[r * W + c]);
    for (const [ch, c, r] of marks) {
        if (ch === "S") cv.start = { c, r };
        else if (ch === "P") cv.portal = { c, r };
        else if (ch === "*") cv.crystals.push([c, r]);
        else if (ch === "k") cv.levers.push([c, r]);
        else if (ch === "E" || ch === "e") {
            const fly = !SUPPORT.includes(at(c, r + 1));
            const ok = (cc: number) =>
                !STOP_WALK.includes(at(cc, r)) &&
                !STOP_WALK.includes(at(cc, r - 1)) &&
                (fly || SUPPORT.includes(at(cc, r + 1)));
            let a = c,
                b = c;
            while (ok(a - 1)) a--;
            while (ok(b + 1)) b++;
            cv.guardians.push({
                kind: fly ? "fly" : "walk",
                x: c * 8,
                y: (r - 1) * 8,
                dir: ch === "E" ? 1 : -1,
                min: a * 8,
                max: b * 8,
            });
        } else {
            const free = (rr: number) => !STOP_LIFT.includes(at(c, rr));
            let a = r,
                b = r;
            while (free(a - 1)) a--;
            while (free(b + 2)) b++;
            cv.guardians.push({ kind: "lift", x: c * 8, y: r * 8, dir: ch === "V" ? 1 : -1, min: a * 8, max: b * 8 });
        }
    }
    cv.tiles = cells.join("");
    return cv;
}
