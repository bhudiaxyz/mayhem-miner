/**
 * Caverns — the twenty hand-drawn screens, and the parser that turns them into level data.
 *
 * Purpose
 *   Every cavern is one 32 × 16 cell screen drawn as ASCII. Authoring as text keeps a level
 *   readable in a diff and lets scripts/check.ts prove each one is completable.
 *
 * Operations
 *   - CAVERNS: the parsed list, in play order.
 *   - parse(def, n): pads each inner row to 30 cells, wraps it in side walls, adds the solid
 *     ceiling (row 0) and floor (row 15), then lifts the markers (start, portal, pickups,
 *     levers, guardians) out of the grid into typed lists. Guardian patrol bounds are worked
 *     out here from the surrounding cells, so the maps never spell them out.
 *
 * Legend (inner rows 1..14, up to 30 characters each, '.' or missing = air)
 *   #  rock wall: blocks from every side, and can be stood on
 *   =  ledge: one-way, stand on it, jump up through it
 *   ~  crumbling ledge: gives way after you stand on it for a moment
 *   <  >  conveyor: carries you left / right; walking against it holds you still
 *   ^  spikes: deadly to touch
 *   D  door: solid until any lever is pulled
 *   k  lever: touch to open every door in the cavern
 *   *  crystal: collect them all to open the portal
 *   P  portal: top-left cell of a 2 × 2 gate
 *   S  start: the miner's lower body cell (standing on the cell below)
 *   E  e  walking guardian (lower cell), starting right / left. With no ledge under it, it flies.
 *   V  v  vertical guardian (upper cell), starting down / up
 *
 * Usage
 *   import { CAVERNS, W, H } from "./caverns"; game.ts copies a cavern's tiles into mutable state.
 *
 * Highlights
 *   - Walking guardians turn at walls, spikes and ledge ends; flying ones only at walls.
 *     Vertical guardians turn at anything structural in their column.
 *   - All layouts, names and art are original to this project.
 *
 * See also: core/game.ts (rules), scripts/check.ts (reachability proof); DESIGN.md "4. Caverns".
 */
export const W = 32;
export const H = 16;

export interface Guardian {
    kind: "walk" | "fly" | "lift";
    /** Pixel position of the top-left corner (cells are 8 px). */
    x: number;
    y: number;
    dir: 1 | -1;
    /** Patrol range in px along the moving axis. */
    min: number;
    max: number;
}

export interface Cavern {
    n: number;
    name: string;
    /** Seconds of air at the start. */
    air: number;
    /** W × H characters, row-major, markers removed. */
    tiles: string;
    start: { c: number; r: number };
    portal: { c: number; r: number };
    crystals: [number, number][];
    levers: [number, number][];
    guardians: Guardian[];
}

interface Def {
    name: string;
    rows: string[];
}

